const plain=s=>s.replace(/<[^>]*>/g,'').trim();
export function applyKeywordHeadings(html,file,changes) {
 const renamed=new Map();
 html=html.replace(/<(title|h[1-6]|summary)\b([^>]*)>([\s\S]*?)<\/\1>|<p\b([^>]*\bclass="eyebrow"[^>]*)>([\s\S]*?)<\/p>/gi,(whole,tag,attrs,content,pAttrs,pContent)=>{
  tag=tag?.toLowerCase()||'p';attrs=attrs??pAttrs;content=content??pContent;
  const before=plain(content),after=replacement(before,tag,file);
  if(before===after)return whole;
  renamed.set(before,after);changes?.push({file,tag,before,after});
  // Existing heading links/emphasis stay intact; replacements concern their text nodes only.
  let changed=false;
  const updated=content.replace(/(^|>)([^<>]+)(?=<|$)/g,(part,prefix,text)=>{
   if(text.trim()!==before)return part;changed=true;return prefix+text.replace(before,after);
  });
  if(!changed)throw new Error('Heading needs explicit markup handling: '+file+' '+before);
  return '<'+tag+attrs+'>'+updated+'</'+tag+'>';
 });
 // Mirror actual renamed page/question/article names, not unrelated body strings.
 html=html.replace(/(<meta\b[^>]*property="og:title"[^>]*content=")([^"]*)(")/g,(w,a,value,b)=>a+(renamed.get(value)||replacement(value,'title',file))+b);
 html=html.replace(/(data-faq-question=")([^"]*)(")/g,(w,a,value,b)=>a+(renamed.get(value)||value)+b);
 html=html.replace(/(<script\b[^>]*type="application\/ld\+json"[^>]*>)([\s\S]*?)(<\/script>)/g,(w,a,json,b)=>{
  const value=JSON.parse(json);let changed=false;
  function visit(v){if(!v||typeof v!=='object')return;for(const key of Object.keys(v)){if(['name','headline'].includes(key)&&typeof v[key]==='string'&&renamed.has(v[key])){v[key]=renamed.get(v[key]);changed=true;}else visit(v[key]);}}
  visit(value);return changed?a+JSON.stringify(value).replace(/</g,'\\u003c')+b:w;
 });
 return html;
}
